def get_lang() -> str:
    try:
        from flask import session

        lang = session.get("lang", DEFAULT)
        return lang if lang in SUPPORTED else DEFAULT
    except RuntimeError:
        return DEFAULT


def t(key: str) -> str:
    lang = get_lang()
    return TRANSLATIONS.get(lang, TRANSLATIONS[DEFAULT]).get(key, key)
